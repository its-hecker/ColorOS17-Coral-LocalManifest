#!/usr/bin/env python3
"""Measure vendor *source* payload using LFS logical sizes, not pointer bytes.

This is NOT an assembled vendor.img or a prediction of filesystem overhead.
Never mistake a source-file estimate for flashability or guaranteed capacity.
"""
import argparse
import json
import re
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
LOCK = json.loads((ROOT / "sources.lock.json").read_text())
PARTS = ("vendor", "product", "system_ext")
LFS_HEADER = b"version https://git-lfs.github.com/spec/v1\n"


def source_bytes(path):
    if path.is_symlink():
        return 0, "symlink"
    if not path.is_file():
        raise ValueError("Missing tracked file: " + str(path))
    with path.open("rb") as stream:
        probe = stream.read(256)
    if probe.startswith(LFS_HEADER):
        match = re.search(rb"(?m)^size (\d+)$", probe)
        if not match:
            raise ValueError("Invalid Git LFS pointer: " + str(path))
        return int(match.group(1)), "lfs_pointer"
    return path.stat().st_size, "ordinary"


def tracked_paths(root):
    result = subprocess.run(
        ["git", "-C", str(root), "ls-files", "-z", "--",
         *["proprietary/" + x for x in PARTS]],
        check=True, capture_output=True
    )
    return [Path(bytes_part.decode("utf-8", errors="surrogateescape"))
            for bytes_part in result.stdout.split(b"\0") if bytes_part]


def summarize(root, group_size, donor_bytes, reserve=32 * 1024 * 1024):
    counts = {p: {"source_bytes": 0, "tracked_files": 0,
                  "lfs_pointers": 0, "symlinks": 0} for p in PARTS}
    for rel in tracked_paths(root):
        if len(rel.parts) < 3 or rel.parts[1] not in counts:
            continue
        part = rel.parts[1]
        logical_size, kind = source_bytes(root / rel)
        rec = counts[part]
        rec["source_bytes"] += logical_size
        rec["tracked_files"] += 1
        if kind == "lfs_pointer":
            rec["lfs_pointers"] += 1
        if kind == "symlink":
            rec["symlinks"] += 1
    if not counts["vendor"]["tracked_files"]:
        raise ValueError("Vendor proprietary files not found; checkout incomplete")
    room = group_size - donor_bytes - reserve
    if room < 0:
        status = "DONOR_OVERSIZE"
    else:
        status = "UNVERIFIED_VENDOR_IMAGE"
    return {
        "source_tree": str(root.resolve()), "group_bytes": group_size,
        "donor_system_img_bytes": donor_bytes, "reservation_bytes": reserve,
        "max_vendor_img_bytes_before_other_overhead": max(0, room),
        "source_proprietary_payloads": counts,
        "vendor_source_bytes_exceed_room": counts["vendor"]["source_bytes"] > room,
        "status": status,
        "critical_limit": ("The actual signed, aligned vendor.img and lib/modules "
                           "generated by the full ROM build must be measured. "
                           "Source files may include unshipped blobs; Android build "
                           "adds files absent from this source tree. Not a fit proof."),
    }


def main():
    p = argparse.ArgumentParser(description="Read-only Coral vendor source size assessment")
    p.add_argument("--vendor-tree", type=Path, default=ROOT / "work/hardware/vendor")
    p.add_argument("--board-config", type=Path,
                   default=ROOT / "work/hardware/device/BoardConfig-common.mk")
    p.add_argument("--output", type=Path, default=ROOT / "work/vendor-footprint.json")
    a = p.parse_args()
    sys.path.insert(0, str(ROOT / "tools"))
    from partition_budget import group_size
    report = summarize(
        a.vendor_tree.resolve(), group_size(a.board_config),
        LOCK["donor"]["inspected"]["system_img_bytes"]
    )
    a.output.parent.mkdir(parents=True, exist_ok=True)
    a.output.write_text(json.dumps(report, indent=2) + "\n")
    print(json.dumps(report, indent=2))
    if report["status"] == "DONOR_OVERSIZE":
        return 2
    return 0


if __name__ == "__main__":
    try:
        raise SystemExit(main())
    except (OSError, ValueError, subprocess.CalledProcessError) as exc:
        print("ERROR:", exc, file=sys.stderr)
        raise SystemExit(2)
